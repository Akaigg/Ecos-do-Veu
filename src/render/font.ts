const CACHE = new Map<string, { w: number; rows: boolean[][] }>();
export function glyph(ch: string): { w: number; rows: boolean[][] } {
  const cached = CACHE.get(ch);
  if (cached) return cached;
  const raw = RAW[ch] ?? RAW['?'];
  const rows = raw.split('|').map((r) => [...r].map((x) => x === '#'));
  const g = { w: rows[0].length, rows };
  CACHE.set(ch, g);
  return g;
}
